export function langOf(code: string | null | undefined): Lang {
  return LANGS.find((l) => l.code === code) ?? LANGS[0];
}

/** The phone's own language, if Amader has it. Matches "bn-BD" to "bn" and "zh-TW" to traditional Chinese. */
export function phoneLang(tags: string[]): Lang | null {
  for (const tag of tags) {
    const lower = tag.toLowerCase();
    if (/^zh-(tw|hk|mo|hant)/.test(lower)) return langOf('zh-Hant');
    const found = LANGS.find((l) => l.code.toLowerCase() === lower) ?? LANGS.find((l) => l.code.toLowerCase() === lower.split('-')[0]);
    if (found) return found;
  }
  return null;
}

