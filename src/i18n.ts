const DEVANAGARI_DIGITS = '०१२३४५६७८९';

/** Numbers in the script people read: Bangla digits for Bangla. Hindi keeps 0-9, which most Hindi apps use. */
export function digits(text: string, code: string | null | undefined): string {
  if (code === 'bn') return text.replace(/[0-9]/g, (d) => BANGLA_DIGITS[Number(d)]);
  if (code === 'ne' || code === 'mr') return text.replace(/[0-9]/g, (d) => DEVANAGARI_DIGITS[Number(d)]);
  return text;
}

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(code: string | null | undefined): Translate {
  const dict = DICTS[code ?? 'en'] ?? {};
  return (key, vars) => {
    let text = dict[key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(typeof v === 'number' ? digits(String(v), code) : v);
    return text;
  };
}
